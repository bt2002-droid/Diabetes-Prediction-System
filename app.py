"""
app.py
------
Streamlit web application for the Diabetes Prediction project.

Run with:
    streamlit run app.py

Requires that train_models.py has already been run successfully, so that
the 'models/' folder contains the trained models, scaler, and saved
evaluation results.
"""

import os
import json
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import streamlit as st

# --------------------------------------------------------------------------
# PAGE CONFIG
# --------------------------------------------------------------------------
st.set_page_config(
    page_title="Diabetes Prediction System",
    page_icon="🩺",
    layout="wide",
)

MODELS_DIR = "models"

FEATURE_INFO = {
    "Pregnancies": ("Number of times pregnant", 0, 20, 1, 3),
    "Glucose": ("Plasma glucose concentration (mg/dL)", 0, 250, 1, 120),
    "BloodPressure": ("Diastolic blood pressure (mm Hg)", 0, 150, 1, 70),
    "SkinThickness": ("Triceps skin fold thickness (mm)", 0, 100, 1, 20),
    "Insulin": ("2-Hour serum insulin (mu U/mL)", 0, 900, 1, 80),
    "BMI": ("Body Mass Index (weight in kg/(height in m)^2)", 0.0, 70.0, 0.1, 25.0),
    "DiabetesPedigreeFunction": ("Diabetes pedigree function (genetic risk score)", 0.0, 3.0, 0.01, 0.5),
    "Age": ("Age (years)", 1, 120, 1, 30),
}

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.pkl",
    "Decision Tree": "decision_tree.pkl",
    "Random Forest": "random_forest.pkl",
    "SVM": "svm.pkl",
}

DISCLAIMER = (
    "This project is for educational purposes only. The prediction is "
    "generated by a machine learning model and should not be considered a "
    "medical diagnosis. Consult a qualified healthcare professional for "
    "medical advice."
)


# --------------------------------------------------------------------------
# CACHED LOADERS
# --------------------------------------------------------------------------
@st.cache_resource
def artifacts_exist():
    required = ["scaler.pkl", "feature_names.pkl", "metrics.csv", "confusion_matrices.pkl"]
    required += list(MODEL_FILES.values())
    return all(os.path.exists(os.path.join(MODELS_DIR, f)) for f in required)


@st.cache_resource
def load_model(name):
    return joblib.load(os.path.join(MODELS_DIR, MODEL_FILES[name]))


@st.cache_resource
def load_scaler():
    return joblib.load(os.path.join(MODELS_DIR, "scaler.pkl"))


@st.cache_resource
def load_feature_names():
    return joblib.load(os.path.join(MODELS_DIR, "feature_names.pkl"))


@st.cache_data
def load_metrics():
    return pd.read_csv(os.path.join(MODELS_DIR, "metrics.csv"), index_col=0)


@st.cache_resource
def load_confusion_matrices():
    return joblib.load(os.path.join(MODELS_DIR, "confusion_matrices.pkl"))


@st.cache_data
def load_feature_importance():
    path = os.path.join(MODELS_DIR, "feature_importance.csv")
    if os.path.exists(path):
        return pd.read_csv(path, index_col=0)
    return None


@st.cache_data
def load_best_model_name():
    path = os.path.join(MODELS_DIR, "best_model.json")
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)["best_model"]
    return None


# --------------------------------------------------------------------------
# SIDEBAR NAVIGATION
# --------------------------------------------------------------------------
st.sidebar.title("🩺 Diabetes Prediction System")
page = st.sidebar.radio(
    "Navigate",
    ["🏠 Home", "🔮 Prediction", "📊 Model Comparison", "📈 Confusion Matrices",
     "⭐ Feature Importance", "ℹ️ About Project"],
)

st.sidebar.markdown("---")
st.sidebar.caption(DISCLAIMER)

if not artifacts_exist():
    st.error(
        "Trained model files were not found in the 'models/' folder.\n\n"
        "Please run the training script first:\n\n"
        "    python train_models.py\n\n"
        "Make sure 'diabetes.csv' is in the project root before running it."
    )
    st.stop()


# --------------------------------------------------------------------------
# PAGE: HOME
# --------------------------------------------------------------------------
if page == "🏠 Home":
    st.title("🩺 Diabetes Prediction System")
    st.subheader("Machine Learning-based Diabetes Risk Prediction — Comparison of 4 Models")

    st.write(
        """
        This project predicts the likelihood of diabetes in a patient using
        machine learning, based on the well-known **Pima Indians Diabetes
        Dataset**. Four different classification models were trained and
        compared, so you can see how different algorithms perform on the
        same medical data.
        """
    )

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("#### Models used")
        st.markdown(
            "- Logistic Regression\n"
            "- Decision Tree\n"
            "- Random Forest\n"
            "- Support Vector Machine (SVM)"
        )
    with col2:
        st.markdown("#### What you can do here")
        st.markdown(
            "- Predict diabetes risk from patient measurements\n"
            "- Compare model performance (accuracy, precision, recall, F1)\n"
            "- View confusion matrices for each model\n"
            "- Explore which features matter most"
        )

    best = load_best_model_name()
    if best:
        st.success(f"Best performing model on this dataset (highest F1 Score): **{best}**")

    st.warning(DISCLAIMER)


# --------------------------------------------------------------------------
# PAGE: PREDICTION
# --------------------------------------------------------------------------
elif page == "🔮 Prediction":
    st.title("🔮 Predict Diabetes Risk")
    st.write("Enter the patient's medical measurements below.")

    feature_names = load_feature_names()

    model_choice = st.selectbox(
        "Select Machine Learning Model",
        list(MODEL_FILES.keys()),
    )

    st.markdown("#### Patient Details")
    col1, col2 = st.columns(2)
    inputs = {}

    half = len(feature_names) // 2 + len(feature_names) % 2
    for i, feat in enumerate(feature_names):
        label, min_v, max_v, step, default = FEATURE_INFO[feat]
        target_col = col1 if i < half else col2
        with target_col:
            inputs[feat] = st.number_input(
                f"{feat}",
                min_value=float(min_v),
                max_value=float(max_v),
                value=float(default),
                step=float(step),
                help=label,
            )

    if st.button("Predict Diabetes Risk", type="primary"):
        scaler = load_scaler()
        model = load_model(model_choice)

        input_df = pd.DataFrame([inputs])[feature_names]
        input_scaled = scaler.transform(input_df)

        prediction = model.predict(input_scaled)[0]

        st.markdown("---")
        st.markdown("### Result")

        if hasattr(model, "predict_proba"):
            proba = model.predict_proba(input_scaled)[0]
            prob_diabetes = proba[1]
            prob_no_diabetes = proba[0]
        else:
            prob_diabetes = None
            prob_no_diabetes = None

        if prediction == 1:
            st.error("### 🔴 Diabetes Risk Detected")
        else:
            st.success("### 🟢 No Diabetes Risk")

        if prob_diabetes is not None:
            c1, c2 = st.columns(2)
            c1.metric("Probability of No Diabetes", f"{prob_no_diabetes * 100:.1f}%")
            c2.metric("Probability of Diabetes", f"{prob_diabetes * 100:.1f}%")
            st.progress(float(prob_diabetes))

        st.info(f"Prediction made using: **{model_choice}**")
        st.warning(DISCLAIMER)


# --------------------------------------------------------------------------
# PAGE: MODEL COMPARISON
# --------------------------------------------------------------------------
elif page == "📊 Model Comparison":
    st.title("📊 Model Comparison")

    metrics_df = load_metrics()
    st.dataframe(metrics_df.style.format("{:.4f}").highlight_max(axis=0, color="#c6f6d5"))

    best_model_name = metrics_df["F1 Score"].idxmax()
    st.success(f"Best-performing model based on F1 Score: **{best_model_name}**")
    st.caption(
        "F1 Score is used as the primary comparison metric because it "
        "balances precision and recall, which matters for medical "
        "prediction tasks where both false positives and false negatives "
        "carry real costs."
    )

    st.markdown("#### Comparison Chart")
    fig, ax = plt.subplots(figsize=(9, 5))
    metrics_df.plot(kind="bar", ax=ax)
    ax.set_ylabel("Score")
    ax.set_xlabel("Model")
    ax.set_title("Model Performance Comparison")
    ax.set_ylim(0, 1)
    ax.legend(loc="lower right")
    plt.xticks(rotation=20)
    st.pyplot(fig)


# --------------------------------------------------------------------------
# PAGE: CONFUSION MATRICES
# --------------------------------------------------------------------------
elif page == "📈 Confusion Matrices":
    st.title("📈 Confusion Matrices")

    st.write(
        """
        A confusion matrix shows how many predictions were correct or
        incorrect, broken down by class:

        - **True Positive (TP):** Model correctly predicted diabetes.
        - **True Negative (TN):** Model correctly predicted no diabetes.
        - **False Positive (FP):** Model predicted diabetes, but patient does not have it.
        - **False Negative (FN):** Model predicted no diabetes, but patient actually has it.

        For diabetes prediction, **False Negatives are especially dangerous** —
        a patient who actually has diabetes but is told they don't may not
        seek treatment in time. This is why **Recall** (the model's ability
        to catch actual diabetes cases) is a critical metric alongside
        accuracy.
        """
    )

    cms = load_confusion_matrices()

    cols = st.columns(2)
    for i, (name, cm) in enumerate(cms.items()):
        with cols[i % 2]:
            st.markdown(f"**{name}**")
            fig, ax = plt.subplots(figsize=(4, 3.3))
            sns.heatmap(
                cm, annot=True, fmt="d", cmap="Blues", cbar=False,
                xticklabels=["No Diabetes", "Diabetes"],
                yticklabels=["No Diabetes", "Diabetes"],
                ax=ax,
            )
            ax.set_xlabel("Predicted")
            ax.set_ylabel("Actual")
            st.pyplot(fig)

            tn, fp, fn, tp = cm.ravel()
            st.caption(f"TP={tp}  TN={tn}  FP={fp}  FN={fn}")


# --------------------------------------------------------------------------
# PAGE: FEATURE IMPORTANCE
# --------------------------------------------------------------------------
elif page == "⭐ Feature Importance":
    st.title("⭐ Feature Importance")

    importance_df = load_feature_importance()

    if importance_df is None or "Random Forest" not in importance_df.columns:
        st.info("Feature importance data not available. Please re-run train_models.py.")
    else:
        st.write(
            "Feature importance shows how much each input feature "
            "contributed to the Random Forest model's decisions."
        )

        rf_importance = importance_df["Random Forest"].sort_values(ascending=True)

        fig, ax = plt.subplots(figsize=(8, 5))
        ax.barh(rf_importance.index, rf_importance.values, color="#2b6cb0")
        ax.set_xlabel("Importance")
        ax.set_title("Random Forest — Feature Importance")
        st.pyplot(fig)

        st.dataframe(importance_df.sort_values("Random Forest", ascending=False))

        st.warning(
            "⚠️ Feature importance indicates how useful a feature was for "
            "the model's predictions. It does **not** prove medical "
            "causation — a feature being 'important' to the model does not "
            "mean it directly causes diabetes."
        )


# --------------------------------------------------------------------------
# PAGE: ABOUT
# --------------------------------------------------------------------------
elif page == "ℹ️ About Project":
    st.title("ℹ️ About This Project")

    st.markdown("#### Dataset")
    st.write(
        "Pima Indians Diabetes Dataset — a medical dataset of female "
        "patients used to predict the onset of diabetes based on "
        "diagnostic measurements."
    )

    st.markdown("#### Input Features")
    st.markdown(
        "- Pregnancies\n"
        "- Glucose\n"
        "- BloodPressure\n"
        "- SkinThickness\n"
        "- Insulin\n"
        "- BMI\n"
        "- DiabetesPedigreeFunction\n"
        "- Age"
    )

    st.markdown("#### Target Variable")
    st.write("Outcome — 0 = No Diabetes, 1 = Diabetes")

    st.markdown("#### Machine Learning Models")
    st.markdown(
        "- Logistic Regression\n"
        "- Decision Tree\n"
        "- Random Forest\n"
        "- Support Vector Machine (SVM)"
    )

    st.markdown("#### Project Limitations")
    st.markdown(
        "- The dataset only includes female patients of Pima Indian heritage, "
        "so results may not generalize to all populations.\n"
        "- The dataset is relatively small, which limits model robustness.\n"
        "- This is an educational project, not a certified medical tool.\n"
        "- Feature importance does not imply medical causation."
    )

    st.warning(DISCLAIMER)
